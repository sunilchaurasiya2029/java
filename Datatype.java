public class Datatype {
    public static void main(String args[]){
        byte b = 8; // range -128 to 127
        System.out.println(b);
        char ch = 'a'; // only character
        System.out.println(ch);
        boolean b1 = true; // only true or false
        System.out.println(b1);
        float price = 19.88f; // only decimal value and range 3.4e-038 to 3.4e+038
        System.out.println(price);
        short n = 340; // range -32768 to 32767
        System.out.println(n);
        // int range -2147483648 to 2147483647
        // long range -9223372036854775808 to 9223372036854775807
        // double range 1.7e-308 to 1.7e+308
    }
    
}
